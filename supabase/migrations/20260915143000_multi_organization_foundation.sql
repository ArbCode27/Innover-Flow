CREATE TABLE IF NOT EXISTS public.organization_members (
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  agent_id integer NOT NULL REFERENCES public.agents(id) ON DELETE CASCADE,
  role text NOT NULL DEFAULT 'advisor'
    CHECK (role IN ('owner', 'admin', 'supervisor', 'advisor')),
  status text NOT NULL DEFAULT 'active'
    CHECK (status IN ('active', 'invited', 'inactive')),
  joined_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (organization_id, agent_id)
);

-- Keep organization_id directly on high-volume/domain tables. This makes
-- authorization predicates, Realtime filters and indexes deterministic.
DO $$
DECLARE
  table_name text;
  tenant_tables text[] := ARRAY[
    'agents',
    'clients',
    'conversations',
    'messages',
    'tickets',
    'labels',
    'quick_replies',
    'conversation_history',
    'history_messages',
    'crm_settings',
    'crm_payments',
    'crm_settings_history',
    'ai_tool_invocations',
    'ai_runs'
  ];
BEGIN
  FOREACH table_name IN ARRAY tenant_tables LOOP
    IF to_regclass('public.' || table_name) IS NOT NULL THEN
      EXECUTE format(
        'ALTER TABLE public.%I ADD COLUMN IF NOT EXISTS organization_id uuid REFERENCES public.organizations(id)',
        table_name
      );
      EXECUTE format(
        'UPDATE public.%I SET organization_id = $1 WHERE organization_id IS NULL',
        table_name
      ) USING '00000000-0000-4000-8000-000000000001'::uuid;
      EXECUTE format(
        'ALTER TABLE public.%I ALTER COLUMN organization_id SET DEFAULT %L::uuid',
        table_name,
        '00000000-0000-4000-8000-000000000001'
      );
      EXECUTE format(
        'ALTER TABLE public.%I ALTER COLUMN organization_id SET NOT NULL',
        table_name
      );
      EXECUTE format(
        'CREATE INDEX IF NOT EXISTS %I ON public.%I (organization_id)',
        table_name || '_organization_id_idx',
        table_name
      );
    END IF;
  END LOOP;
END $$;

