CREATE OR REPLACE FUNCTION public.capture_conversation_metrics()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
BEGIN
  IF TG_OP = 'INSERT' THEN
    INSERT INTO public.conversation_events (
      organization_id, conversation_id, agent_id, event_type, occurred_at
    ) VALUES (
      NEW.organization_id, NEW.id, NEW.agent_id, 'created',
      coalesce(NEW.created_at, now())
    );
    RETURN NEW;
  END IF;

  IF NEW.agent_id IS DISTINCT FROM OLD.agent_id AND NEW.agent_id IS NOT NULL THEN
    UPDATE public.conversation_assignments
    SET unassigned_at = now()
    WHERE organization_id = NEW.organization_id
      AND conversation_id = NEW.id
      AND unassigned_at IS NULL;

    INSERT INTO public.conversation_assignments (
      organization_id, conversation_id, agent_id, assigned_at
    ) VALUES (NEW.organization_id, NEW.id, NEW.agent_id, now());

    INSERT INTO public.conversation_events (
      organization_id, conversation_id, agent_id, event_type
    ) VALUES (
      NEW.organization_id,
      NEW.id,
      NEW.agent_id,
      CASE WHEN OLD.agent_id IS NULL THEN 'assigned' ELSE 'transferred' END
    );
  END IF;

  IF NEW.status = 'resuelto' AND OLD.status IS DISTINCT FROM 'resuelto' THEN
    INSERT INTO public.conversation_events (
      organization_id, conversation_id, agent_id, event_type
    ) VALUES (NEW.organization_id, NEW.id, NEW.agent_id, 'resolved');
  ELSIF OLD.status = 'resuelto' AND NEW.status IS DISTINCT FROM 'resuelto' THEN
    INSERT INTO public.conversation_events (
      organization_id, conversation_id, agent_id, event_type
    ) VALUES (NEW.organization_id, NEW.id, NEW.agent_id, 'reopened');
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS conversations_metrics_trigger ON public.conversations;
CREATE TRIGGER conversations_metrics_trigger
AFTER INSERT OR UPDATE OF agent_id, status ON public.conversations
FOR EACH ROW EXECUTE FUNCTION public.capture_conversation_metrics();

CREATE OR REPLACE FUNCTION public.capture_first_agent_response()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  conversation_created_at timestamptz;
  conversation_agent_id integer;
BEGIN
  IF NEW.type <> 'out' OR NEW.sender_type <> 'agent' THEN
    RETURN NEW;
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.conversation_events
    WHERE organization_id = NEW.organization_id
      AND conversation_id = NEW.conversation_id
      AND event_type = 'first_response'
  ) THEN
    RETURN NEW;
  END IF;

  SELECT created_at, agent_id
  INTO conversation_created_at, conversation_agent_id
  FROM public.conversations
  WHERE id = NEW.conversation_id
    AND organization_id = NEW.organization_id;

  INSERT INTO public.conversation_events (
    organization_id,
    conversation_id,
    agent_id,
    event_type,
    metadata,
    occurred_at
  ) VALUES (
    NEW.organization_id,
    NEW.conversation_id,
    conversation_agent_id,
    'first_response',
    jsonb_build_object(
      'duration_ms',
      greatest(
        0,
        floor(
          extract(epoch FROM (coalesce(NEW.created_at, now()) - conversation_created_at))
          * 1000
        )
      )
    ),
    coalesce(NEW.created_at, now())
  );

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS messages_first_response_trigger ON public.messages;
CREATE TRIGGER messages_first_response_trigger
AFTER INSERT ON public.messages
FOR EACH ROW EXECUTE FUNCTION public.capture_first_agent_response();
