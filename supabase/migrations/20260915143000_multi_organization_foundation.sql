CREATE TABLE IF NOT EXISTS public.organization_integrations (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  provider text NOT NULL CHECK (provider IN ('wispro', 'whatsapp')),
  status text NOT NULL DEFAULT 'disconnected'
    CHECK (status IN ('disconnected', 'pending', 'connected', 'error')),
  config jsonb NOT NULL DEFAULT '{}'::jsonb,
  credentials_encrypted text,
  last_verified_at timestamptz,
  last_error text,
  configured_by integer REFERENCES public.agents(id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (organization_id, provider)
);

CREATE INDEX IF NOT EXISTS organization_integrations_provider_idx
  ON public.organization_integrations (provider, organization_id);

CREATE TABLE IF NOT EXISTS public.conversation_assignments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  conversation_id bigint NOT NULL,
  agent_id integer REFERENCES public.agents(id) ON DELETE SET NULL,
  assigned_by integer REFERENCES public.agents(id) ON DELETE SET NULL,
  assigned_at timestamptz NOT NULL DEFAULT now(),
  unassigned_at timestamptz,
  reason text
);

CREATE INDEX IF NOT EXISTS conversation_assignments_metrics_idx
  ON public.conversation_assignments (organization_id, agent_id, assigned_at DESC);

CREATE TABLE IF NOT EXISTS public.conversation_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id uuid NOT NULL REFERENCES public.organizations(id) ON DELETE CASCADE,
  conversation_id bigint NOT NULL,
  agent_id integer REFERENCES public.agents(id) ON DELETE SET NULL,
  event_type text NOT NULL CHECK (
    event_type IN (
      'created',
      'assigned',
      'first_response',
      'resolved',
      'reopened',
      'transferred'
    )
  ),
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb,
  occurred_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS conversation_events_metrics_idx
  ON public.conversation_events (
    organization_id,
    event_type,
    occurred_at DESC
  );

-- New organization-management tables are server-only. Existing domain tables
-- remain compatible with the current client while data access is moved to
-- authenticated server routes.
ALTER TABLE public.organizations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.organization_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.organization_integrations ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversation_assignments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.conversation_events ENABLE ROW LEVEL SECURITY;

DO $$
DECLARE
  table_name text;
  protected_tables text[] := ARRAY[
    'organizations',
    'organization_members',
    'organization_integrations',
    'conversation_assignments',
    'conversation_events'
  ];
BEGIN
  FOREACH table_name IN ARRAY protected_tables LOOP
    EXECUTE format(
      'DROP POLICY IF EXISTS service_role_all ON public.%I',
      table_name
    );
    EXECUTE format(
      'CREATE POLICY service_role_all ON public.%I FOR ALL TO service_role USING (true) WITH CHECK (true)',
      table_name
    );
  END LOOP;
END $$;

-- Domain data is available only through authenticated Next.js routes using
-- service_role. The browser anon key cannot bypass tenant checks.
DO $$
DECLARE
  table_name text;
  domain_tables text[] := ARRAY[
    'agents',
    'clients',
    'conversations',
    'messages',
    'tickets',
    'labels',
    'quick_replies',
    'conversation_history',
    'history_messages',
    'crm_settings',
    'crm_payments',
    'ai_runs',
    'ai_tool_invocations'
  ];
BEGIN
  FOREACH table_name IN ARRAY domain_tables LOOP
    IF to_regclass('public.' || table_name) IS NOT NULL THEN
      EXECUTE format('ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY', table_name);
      EXECUTE format('DROP POLICY IF EXISTS service_role_all ON public.%I', table_name);
      EXECUTE format(
        'CREATE POLICY service_role_all ON public.%I FOR ALL TO service_role USING (true) WITH CHECK (true)',
        table_name
      );
    END IF;
  END LOOP;
END $$;

