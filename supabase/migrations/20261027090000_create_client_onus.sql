CREATE TABLE IF NOT EXISTS public.client_onus (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  client_id BIGINT REFERENCES public.clients(id) ON DELETE CASCADE,
  onu_external_id TEXT NOT NULL UNIQUE,
  sn TEXT NOT NULL,
  board INTEGER,
  port INTEGER,
  rx_signal NUMERIC(5,2),
  status TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Índices para búsquedas rápidas
CREATE INDEX IF NOT EXISTS client_onus_client_id_idx ON public.client_onus (client_id);
CREATE INDEX IF NOT EXISTS client_onus_onu_external_id_idx ON public.client_onus (onu_external_id);
